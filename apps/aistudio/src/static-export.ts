// The production website as plain files (documentation 7.7): a published release rendered once, so any web hosting
// serves it without SiteTiller. Pages of rendering.json are rendered from their templates with the frozen content;
// every other file is copied; templates, rendering.json, forms.json and architecture.txt stay private. Each contact form becomes a PHP
// script with its definition and recipient built in (the hosting sends the mail).
import { readdir, readFile, lstat } from 'node:fs/promises';
import { join } from 'node:path';
import { renderCmsPage, renderingPages } from './cms-render.ts';
import { privateSiteFiles } from './site-policy.ts';
import { formDefinitions, recipientFromCms, type FormDefinition } from './contact-forms.ts';
const textFile = /\.(html?|css|js|mjs|json|txt|svg|xml|md|csv|webmanifest)$/i;
// A release directory as relative path → bytes (symbolic links are refused).
export async function readRelease(directory: string) {
  const files: Record<string, Buffer> = {};
  const walk = async (dir: string, prefix: string) => {
    for (const item of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, item.name),
        name = prefix + item.name;
      if (item.isSymbolicLink() || (await lstat(path)).isSymbolicLink()) throw Error('Symbolic link in release');
      if (item.isDirectory()) await walk(path, name + '/');
      else if (item.isFile()) files[name] = await readFile(path);
    }
  };
  await walk(directory, '');
  return files;
}
export type ExportOptions = { siteUrl: string; mailFrom?: string; mailTo?: string };
export async function staticExport(release: Record<string, Buffer>, options: ExportOptions) {
  const texts: Record<string, string> = {};
  for (const [name, bytes] of Object.entries(release))
    if (textFile.test(name)) texts['site/' + name] = bytes.toString('utf8');
  const pages = renderingPages(texts),
    hidden = new Set(['rendering.json', 'forms.json', ...privateSiteFiles, ...Object.values(pages).map((t) => t.slice(5))]),
    out: Record<string, Buffer> = {};
  for (const [name, bytes] of Object.entries(release)) if (!hidden.has(name)) out[name] = bytes;
  for (const page of Object.keys(pages)) {
    const html = await renderCmsPage(page, texts, false);
    if (html) out[page.slice(5)] = Buffer.from(html);
  }
  const forms = formDefinitions(texts),
    host = new URL(options.siteUrl).hostname.replace(/^www\./, '');
  for (const [id, form] of Object.entries(forms)) {
    const to = (await recipientFromCms(form, texts, false)) || options.mailTo || '';
    const script = Buffer.from(
      formScript(id, form, {
        to,
        from: options.mailFrom || 'info@' + host,
        origin: new URL(options.siteUrl).origin,
      }),
    );
    out['__sitetiller/forms/' + id + '.php'] = script;
    // Websites made before the .php endpoint post to /__sitetiller/forms/<id>.
    out['__sitetiller/forms/' + id + '/index.php'] = script;
  }
  return out;
}
// The same validation and JSON answers as the website runtime (contact-forms.ts), in PHP 8.
export function formScript(id: string, form: FormDefinition, delivery: { to: string; from: string; origin: string }) {
  const config = JSON.stringify({
    id,
    label: form.label,
    replyTo: form.replyTo || null,
    fields: form.fields.map((f) => ({
      name: f.name,
      label: f.label,
      type: f.type,
      required: f.required === true,
      max: f.maxLength ?? (f.type === 'textarea' ? 5000 : 500),
    })),
    ...delivery,
  });
  return `<?php
// Generated by SiteTiller from forms.json (form "${id}"); every publication replaces it.
declare(strict_types=1);
$config = json_decode(base64_decode('${Buffer.from(config).toString('base64')}'), true);
function answer(int $status, array $body): never {
  http_response_code($status);
  header('Content-Type: application/json; charset=utf-8');
  header('Cache-Control: no-store');
  header('X-Content-Type-Options: nosniff');
  echo json_encode($body, JSON_UNESCAPED_UNICODE);
  exit;
}
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
  header('Allow: POST');
  answer(405, ['ok' => false, 'message' => 'Použijte odeslání formuláře.']);
}
if (($_SERVER['HTTP_ORIGIN'] ?? '') !== $config['origin'])
  answer(403, ['ok' => false, 'message' => 'Nepovolený původ požadavku.']);
// At most 10 submissions per address in 10 minutes.
$slot = sys_get_temp_dir() . '/sitetiller-form-' . hash('sha256', $config['origin'] . '|' . ($_SERVER['REMOTE_ADDR'] ?? ''));
$now = time();
$times = array_values(array_filter((array) json_decode((string) @file_get_contents($slot), true), fn($t) => is_int($t) && $t > $now - 600));
$times[] = $now;
@file_put_contents($slot, json_encode($times), LOCK_EX);
if (count($times) > 10) answer(429, ['ok' => false, 'message' => 'Příliš mnoho pokusů. Zkuste to později.']);
$mime = strtolower(trim(explode(';', $_SERVER['CONTENT_TYPE'] ?? '')[0]));
if (!in_array($mime, ['application/json', 'application/x-www-form-urlencoded'], true))
  answer(415, ['ok' => false, 'message' => 'Nepodporovaný formát.']);
$text = (string) file_get_contents('php://input', false, null, 0, 32001);
if (strlen($text) > 32000) answer(413, ['ok' => false, 'message' => 'Zpráva je příliš dlouhá.']);
if ($mime === 'application/json') $input = json_decode($text, true);
else {
  $input = [];
  foreach (explode('&', $text) as $pair) {
    if ($pair === '') continue;
    [$key, $value] = array_pad(explode('=', $pair, 2), 2, '');
    $key = urldecode($key);
    if (array_key_exists($key, $input)) answer(400, ['ok' => false, 'message' => 'Neplatná zpráva.']);
    $input[$key] = urldecode($value);
  }
}
if (!is_array($input) || array_is_list($input) && $input !== []) answer(400, ['ok' => false, 'message' => 'Neplatná zpráva.']);
if (!empty($input['_website'])) answer(400, ['ok' => false, 'message' => 'Zprávu nelze přijmout.']);
$names = array_column($config['fields'], 'name');
foreach (array_keys($input) as $key)
  if ($key !== '_website' && !in_array($key, $names, true))
    answer(422, ['ok' => false, 'message' => 'Formulář obsahuje neznámá pole.']);
$errors = [];
$values = [];
foreach ($config['fields'] as $f) {
  $raw = $input[$f['name']] ?? ($f['type'] === 'checkbox' ? false : '');
  if ($f['type'] === 'checkbox') {
    if (!in_array($raw, [true, false, 'true', 'false'], true)) $errors[$f['name']] = 'Vyberte ano/ne.';
    $values[$f['name']] = $raw === true || $raw === 'true' ? 'true' : 'false';
    if ($f['required'] && $values[$f['name']] !== 'true') $errors[$f['name']] = 'Zaškrtněte toto pole.';
    continue;
  }
  if (!is_string($raw)) {
    $errors[$f['name']] = 'Vyplňte text.';
    continue;
  }
  $v = trim($raw);
  $values[$f['name']] = $v;
  if ($f['required'] && $v === '') $errors[$f['name']] = 'Vyplňte toto pole.';
  if (mb_strlen($v) > $f['max']) $errors[$f['name']] = 'Text je příliš dlouhý.';
  if ($f['type'] === 'email' && $v !== '' && !preg_match('/^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/', $v))
    $errors[$f['name']] = 'Vyplňte platný e-mail.';
}
if ($errors) answer(422, ['ok' => false, 'message' => 'Zkontrolujte vyplněná pole.', 'errors' => $errors]);
$body = [];
foreach ($config['fields'] as $f)
  $body[] = $f['label'] . ":\\n" . ($f['type'] === 'checkbox' ? ($values[$f['name']] === 'true' ? 'Ano' : 'Ne') : $values[$f['name']]);
$headers = ['From' => $config['from'], 'Content-Type' => 'text/plain; charset=UTF-8'];
$reply = $config['replyTo'] ? ($values[$config['replyTo']] ?? '') : '';
if ($reply !== '' && !preg_match('/[\\r\\n]/', $reply)) $headers['Reply-To'] = $reply;
$sent = $config['to'] !== '' && mail(
  $config['to'],
  '=?UTF-8?B?' . base64_encode($config['label']) . '?=',
  implode("\\n\\n", $body),
  $headers,
);
if (!$sent) answer(503, ['ok' => false, 'message' => 'Zprávu se nepodařilo odeslat. Zkuste to později nebo použijte přímý kontakt.']);
answer(200, ['ok' => true, 'preview' => false, 'message' => 'Zpráva byla odeslána.']);
`;
}
